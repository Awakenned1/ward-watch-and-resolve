// Generates src/lib/db-types.ts (Supabase-style `Database` type) from db/migrations by applying
// them to an embedded Postgres and introspecting the public schema.
// Run: node db/gen-types.mjs   (PGlite resolved from PGLITE_PATH or node_modules)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { PGlite } = await import(
  process.env.PGLITE_PATH ? pathToFileURL(process.env.PGLITE_PATH).href : "@electric-sql/pglite"
);
const db = new PGlite();
await db.exec(readFileSync(join(here, "tests", "supabase-stubs.sql"), "utf8"));
const dir = join(here, "migrations");
for (const f of readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()) {
  await db.exec(readFileSync(join(dir, f), "utf8"));
}

const enums = new Map();
for (const r of (
  await db.query(`SELECT t.typname, e.enumlabel FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = 'public' ORDER BY t.typname, e.enumsortorder`)
).rows) {
  if (!enums.has(r.typname)) enums.set(r.typname, []);
  enums.get(r.typname).push(r.enumlabel);
}

const scalar = (udt) => {
  if (udt.startsWith("_")) return `${scalar(udt.slice(1))}[]`;
  if (enums.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(udt)) return "number";
  if (udt === "bool") return "boolean";
  if (["json", "jsonb"].includes(udt)) return "Json";
  if (udt === "void") return "undefined";
  return "string";
};

const columns = (
  await db.query(`SELECT c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default,
      c.is_identity, c.is_generated
    FROM information_schema.columns c JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
    ORDER BY c.table_name, c.ordinal_position`)
).rows;
const fks = (
  await db.query(`SELECT con.conname, rel.relname AS table_name, frel.relname AS ref_table,
      (SELECT array_agg(a.attname ORDER BY k.n) FROM unnest(con.conkey) WITH ORDINALITY k(attnum, n)
         JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum) AS cols,
      (SELECT array_agg(a.attname ORDER BY k.n) FROM unnest(con.confkey) WITH ORDINALITY k(attnum, n)
         JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum) AS ref_cols
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid JOIN pg_namespace n ON n.oid = rel.relnamespace
    JOIN pg_class frel ON frel.oid = con.confrelid JOIN pg_namespace fn ON fn.oid = frel.relnamespace
    WHERE con.contype = 'f' AND n.nspname = 'public' AND fn.nspname = 'public'
    ORDER BY rel.relname, con.conname`)
).rows;

const tables = new Map();
for (const c of columns) {
  if (!tables.has(c.table_name)) tables.set(c.table_name, []);
  tables.get(c.table_name).push(c);
}

const ind = (n) => "  ".repeat(n);
let out = `// Generated by db/gen-types.mjs from db/migrations. Do not edit by hand; re-run the script.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: { PostgrestVersion: "14.18" };
  public: {
    Tables: {
`;
for (const [name, cols] of tables) {
  const row = cols.map(
    (c) =>
      `${ind(5)}${c.column_name}: ${scalar(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`,
  );
  const ins = cols
    .filter((c) => c.is_generated !== "ALWAYS" && !(c.is_identity === "YES"))
    .map((c) => {
      const optional = c.is_nullable === "YES" || c.column_default !== null;
      return `${ind(5)}${c.column_name}${optional ? "?" : ""}: ${scalar(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
    });
  const upd = cols
    .filter((c) => c.is_generated !== "ALWAYS" && !(c.is_identity === "YES"))
    .map(
      (c) =>
        `${ind(5)}${c.column_name}?: ${scalar(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`,
    );
  const rels = fks
    .filter((f) => f.table_name === name)
    .map(
      (f) =>
        `${ind(5)}{ foreignKeyName: "${f.conname}"; columns: ${JSON.stringify(f.cols)}; isOneToOne: false; referencedRelation: "${f.ref_table}"; referencedColumns: ${JSON.stringify(f.ref_cols)} },`,
    );
  out += `${ind(3)}${name}: {
${ind(4)}Row: {
${row.join("\n")}
${ind(4)}};
${ind(4)}Insert: {
${ins.join("\n")}
${ind(4)}};
${ind(4)}Update: {
${upd.join("\n")}
${ind(4)}};
${ind(4)}Relationships: [
${rels.join("\n")}
${ind(4)}];
${ind(3)}};
`;
}
out += `${ind(2)}};
${ind(2)}Views: { [_ in never]: never };
${ind(2)}Functions: {
`;

// RPC-callable functions: executable by `authenticated`, not trigger functions.
const fns = (
  await db.query(`SELECT p.proname, p.proargnames, p.proargmodes, p.pronargs, p.pronargdefaults, p.proretset,
      rt.typname AS ret, (SELECT array_agg(t.typname ORDER BY a.n) FROM unnest(coalesce(p.proallargtypes, p.proargtypes::oid[]))
        WITH ORDINALITY a(oid, n) JOIN pg_type t ON t.oid = a.oid) AS argtypes
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace JOIN pg_type rt ON rt.oid = p.prorettype
    WHERE n.nspname = 'public' AND rt.typname <> 'trigger'
      AND has_function_privilege('authenticated', p.oid, 'EXECUTE')
    ORDER BY p.proname`)
).rows;
for (const f of fns) {
  const names = f.proargnames ?? [];
  const modes = f.proargmodes ?? names.map(() => "i");
  const types = f.argtypes ?? [];
  const inputs = [];
  const outputs = [];
  types.forEach((t, i) => {
    const mode = modes[i] ?? "i";
    if (mode === "i" || mode === "b") inputs.push({ name: names[i], type: t });
    if (mode === "o" || mode === "b" || mode === "t") outputs.push({ name: names[i], type: t });
  });
  const firstOptional = inputs.length - (f.pronargdefaults ?? 0);
  const args = inputs.length
    ? `{ ${inputs.map((a, i) => `${a.name}${i >= firstOptional ? "?" : ""}: ${scalar(a.type)}`).join("; ")} }`
    : "never";
  let ret;
  if (outputs.length)
    ret = `{ ${outputs.map((o) => `${o.name}: ${scalar(o.type)}`).join("; ")} }[]`;
  else ret = `${scalar(f.ret)}${f.proretset ? "[]" : ""}`;
  out += `${ind(3)}${f.proname}: { Args: ${args}; Returns: ${ret} };\n`;
}
out += `${ind(2)}};
${ind(2)}Enums: {
${[...enums].map(([k, v]) => `${ind(3)}${k}: ${v.map((x) => JSON.stringify(x)).join(" | ")};`).join("\n")}
${ind(2)}};
${ind(2)}CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

const target = join(here, "..", "src", "lib", "db-types.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${tables.size} tables, ${fns.length} functions, ${enums.size} enums`);
