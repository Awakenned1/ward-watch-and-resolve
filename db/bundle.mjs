// Bundles db/migrations into db/setup-all.sql for pasting into the Supabase SQL Editor.
// It records each migration (same checksums as db/migrate.mjs) so the two methods never conflict.
// Run: node db/bundle.mjs
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "migrations");
const files = readdirSync(dir)
  .filter((f) => /^\d{4}_.+\.sql$/.test(f))
  .sort();

let sql = `-- Ward 109 Resolved: complete database setup (generated by db/bundle.mjs; do not edit).
-- Paste into Supabase Dashboard > SQL Editor and click Run, once, on a new project.
-- Includes: ${files.join(", ")}

BEGIN;

CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC;
CREATE TABLE IF NOT EXISTS app_private.schema_migrations (
  name text PRIMARY KEY,
  checksum text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);
`;
for (const file of files) {
  const body = readFileSync(join(dir, file), "utf8");
  const checksum = createHash("sha256").update(body).digest("hex");
  sql += `\n-- >>> ${file} ${"-".repeat(Math.max(0, 80 - file.length))}\n${body}\n`;
  sql += `INSERT INTO app_private.schema_migrations (name, checksum) VALUES ('${file}', '${checksum}');\n`;
}
sql += `
COMMIT;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(join(here, "setup-all.sql"), sql);
console.log(`wrote db/setup-all.sql (${files.length} migrations, ${sql.length} bytes)`);
